-- OneSpace backend schema v1 (report Section 4, "Mô hình dữ liệu backend").
-- Portable between PostgreSQL and H2 (MODE=PostgreSQL). Times are epoch milliseconds.

CREATE TABLE users (
    id            VARCHAR(40)  PRIMARY KEY,
    phone         VARCHAR(20)  UNIQUE,
    email         VARCHAR(254) UNIQUE,
    password_hash VARCHAR(100),
    name          VARCHAR(100) NOT NULL,
    avatar        VARCHAR(40),
    created_at    BIGINT       NOT NULL
);

CREATE TABLE sessions (
    id                 VARCHAR(40) PRIMARY KEY,
    user_id            VARCHAR(40) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    access_token_hash  VARCHAR(64) NOT NULL UNIQUE,
    access_expires_at  BIGINT      NOT NULL,
    refresh_token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at         BIGINT      NOT NULL
);

CREATE TABLE content_items (
    id           VARCHAR(40)  PRIMARY KEY,
    type         VARCHAR(10)  NOT NULL CHECK (type IN ('video', 'music', 'news')),
    title        VARCHAR(200) NOT NULL,
    creator      VARCHAR(100),
    category     VARCHAR(60),
    duration     VARCHAR(10),
    read_time    VARCHAR(30),
    url          VARCHAR(500),
    thumbnail    VARCHAR(500),
    body         TEXT,
    lyrics       TEXT,
    bpm          INT,
    published_at BIGINT       NOT NULL,
    sort_order   INT          NOT NULL,
    version      INT          NOT NULL DEFAULT 1
);
CREATE INDEX idx_content_type ON content_items(type, sort_order);

CREATE TABLE quiz_questions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id      VARCHAR(40)  NOT NULL REFERENCES content_items(id) ON DELETE CASCADE,
    position     INT          NOT NULL,
    question     VARCHAR(500) NOT NULL,
    options      TEXT         NOT NULL, -- JSON array of strings
    answer_index INT          NOT NULL
);

CREATE TABLE playlists (
    id         VARCHAR(40)  PRIMARY KEY,
    user_id    VARCHAR(40)  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name       VARCHAR(100) NOT NULL,
    version    INT          NOT NULL DEFAULT 1,
    updated_at BIGINT       NOT NULL,
    UNIQUE (user_id, name)
);

CREATE TABLE playlist_items (
    playlist_id VARCHAR(40) NOT NULL REFERENCES playlists(id) ON DELETE CASCADE,
    item_id     VARCHAR(40) NOT NULL REFERENCES content_items(id),
    position    INT         NOT NULL,
    PRIMARY KEY (playlist_id, item_id)
);

CREATE TABLE point_entries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    VARCHAR(40) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_id   VARCHAR(64) NOT NULL UNIQUE, -- client-generated: a retried event is counted once
    source     VARCHAR(60) NOT NULL,
    amount     INT         NOT NULL,
    created_at BIGINT      NOT NULL
);
CREATE INDEX idx_points_user ON point_entries(user_id);

CREATE TABLE daily_missions (
    id          VARCHAR(80)  PRIMARY KEY, -- user_id:date:type
    user_id     VARCHAR(40)  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title       VARCHAR(100) NOT NULL,
    target_type VARCHAR(10)  NOT NULL,
    target      INT          NOT NULL,
    progress    INT          NOT NULL DEFAULT 0,
    completed   BOOLEAN      NOT NULL DEFAULT FALSE,
    date        VARCHAR(10)  NOT NULL,
    version     INT          NOT NULL DEFAULT 1
);
CREATE INDEX idx_missions_user_date ON daily_missions(user_id, date);

CREATE TABLE progress (
    user_id     VARCHAR(40) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_id     VARCHAR(40) NOT NULL REFERENCES content_items(id),
    position_ms BIGINT      NOT NULL,
    version     INT         NOT NULL DEFAULT 1,
    updated_at  BIGINT      NOT NULL,
    PRIMARY KEY (user_id, item_id)
);
CREATE INDEX idx_progress_user_updated ON progress(user_id, updated_at);
